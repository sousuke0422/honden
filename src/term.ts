/**
 * 端末へ出す字の見栄え。
 *
 * 文中の `**強調**` は、書く側にとっては読みやすい印だが、**端末へそのまま出ると
 * ただの記号**である（殿の指摘・2026-08-28「美しさにも欠ける」）。
 * 端末なら太字にし、パイプやファイルへ落ちるなら印ごと外す。
 *
 * 色は使わぬ。太さだけにしておく——端末の配色は人それぞれで、色を決め打てば
 * 読めぬ組み合わせが必ず出る。太さは背景に依らぬ。
 */

const ESC = String.fromCharCode(27);
const BOLD = `${ESC}[1m`;
const UNBOLD = `${ESC}[22m`;

/** 出し先が人の目か（端末か）。パイプ・ファイル・捕獲の先では false。 */
export function isTty(stream: { isTTY?: boolean } = process.stdout): boolean {
  // NO_COLOR は色の話だが、飾りを厭う意思表示として尊ぶ（慣例）。
  if (process.env.NO_COLOR !== undefined) return false;
  return stream.isTTY === true;
}

/**
 * `**…**` を太字にする。端末でなければ印を外すだけ。
 *
 * **飾りのために本文を壊さぬ**のが第一である。素直に「`**` を見たら飾り」と
 * 読むと、glob を潰す——殿の指摘（2026-08-28）で気づいた:
 *
 *   入: Edit(agents/**) と Edit(.cursor/hooks/**) を塞ぐ
 *   出: Edit(agents/) と Edit(.cursor/hooks/) を塞ぐ    ← glob が消えた
 *
 * 二つの glob の `**` を「開き」と「閉じ」と誤読したのである。しかも
 * この文字列は**門の自衛の一覧を出す時に実際に並ぶ**。
 *
 * ゆえに飾りと認めるのを狭める:
 *   - 開きの直後と閉じの直前が空白でないこと（`** 大事 **` は飾りでない）
 *   - 中に改行を跨がぬこと（段を越える飾りは、たいてい誤読である）
 *   - 中に `*` や `/` を含まぬこと（glob と経路を巻き込まぬ）
 *   - **開きの直前が `/` でないこと**——`agents/**` の閉じが飾りの開きと
 *     対になり、間を飾って glob を潰した（試験が捕らえた第二の穴）
 *
 * 迷うたら飾らぬ。**飾り損ねても字は読めるが、壊れた字は読めぬ。**
 */
export function emphasize(s: string, tty: boolean = isTty()): string {
  return s.replace(/(?<![/*])\*\*(?![\s*])([^*\n/]*[^\s*\n/])\*\*/g, tty ? `${BOLD}$1${UNBOLD}` : '$1');
}
